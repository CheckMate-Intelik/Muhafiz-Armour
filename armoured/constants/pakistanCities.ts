export function findPakistanCityByName(name: string): PakistanCity | undefined {
  const q = name.trim().toLowerCase();
  if (!q) return undefined;
  return PAKISTAN_CITIES.find((c) => c.name.toLowerCase() === q);
}

export function filterPakistanCities(query: string): PakistanCity[] {
  const q = query.trim().toLowerCase();
  if (!q) return PAKISTAN_CITIES;
  return PAKISTAN_CITIES.filter((c) => c.name.toLowerCase().includes(q));
}
